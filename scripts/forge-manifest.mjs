#!/usr/bin/env node
/**
 * Renders app/manifest.yml from one template plus the shared tool catalog
 * (packages/core tools.ts), so the Forge actions, their functions, the
 * rovo:mcp tool list and the agent's action list can never drift from the
 * tools the code serves.
 *
 *   node scripts/forge-manifest.mjs           print the rendered manifest
 *   node scripts/forge-manifest.mjs --write   rewrite app/manifest.yml
 *   node scripts/forge-manifest.mjs --check   exit 1 when app/manifest.yml is stale
 *
 * The app id is read from the current manifest and kept, so `forge register`
 * (which writes the real id) and this script can both own the file.
 *
 * Needs the built engine (`npm run build -w @traceflow/core`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = join(root, 'app', 'manifest.yml');
const { TRACEFLOW_TOOLS } = await import(join(root, 'packages', 'core', 'dist', 'index.js'));

export const PLACEHOLDER_APP_ID = 'ari:cloud:ecosystem::app/REPLACE_AFTER_FORGE_REGISTER';

function currentAppId() {
  try {
    const text = readFileSync(manifestPath, 'utf8');
    return /^\s+id:\s*"?(ari:cloud:ecosystem::app\/[^"\s]+)"?\s*$/m.exec(text)?.[1] ?? PLACEHOLDER_APP_ID;
  } catch {
    return PLACEHOLDER_APP_ID;
  }
}

/** JSON strings are valid YAML double-quoted scalars: safe for any text. */
const q = (value) => JSON.stringify(value);

function indent(text, spaces) {
  const pad = ' '.repeat(spaces);
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? pad + line : line))
    .join('\n');
}

const AGENT_PROMPT = `You are TraceFlow, an analyst for engineering organizations. You reveal
knowledge-continuity risks and decision lineage, and every claim you
make must come from the TraceFlow engine, never from your own knowledge.

Rules:
- To answer anything about risks, people, impact, epics or decisions,
  call a TraceFlow action. Use traceflow-investigate for open questions
  in the user's own words; use the specific actions when the user names
  a person, an epic or a decision. Never answer such questions from memory.
- Every action returns a JSON payload built from the site's Jira and
  Confluence records. Relay it faithfully; you may make it friendlier, but
  never add people, record ids, titles or numbers that are not in the payload.
- When traceflow-investigate returns "understood": false, say plainly that
  the question could not be mapped to the connected records, and offer its
  "suggestions" as examples of what to ask. Never guess.
- When an action returns "ok": false, relay its "error" message as it is.
- Keep the payload's caveats: they state what the records cannot prove,
  and every honest answer carries them.
- When the payload has evidence records, offer them (source, id, url when
  present) so the user can open each one.
- Findings are audit-ready evidence, not proof of compliance, and "sole
  contributor" means one recorded editor, never the only person who knows.`;

export function renderManifest(appId = currentAppId()) {
  const functions = [
    `    - key: tf-resolver\n      handler: backend/index.handler`,
    ...TRACEFLOW_TOOLS.map((t) => `    - key: ${t.functionKey}\n      handler: backend/tools.${t.handler}`),
  ].join('\n');

  const actions = TRACEFLOW_TOOLS.map((t) => {
    const lines = [
      `    - key: ${t.actionKey}`,
      `      name: ${q(t.title)}`,
      `      function: ${t.functionKey}`,
      `      actionVerb: GET`,
      `      description: ${q(t.summary)}`,
    ];
    if (t.input) {
      lines.push(
        `      inputs:`,
        `        ${t.input.name}:`,
        `          title: ${q(t.input.title)}`,
        `          type: string`,
        `          required: true`,
        `          description: ${q(t.input.description)}`,
      );
    }
    return lines.join('\n');
  }).join('\n');

  const toolKeys = TRACEFLOW_TOOLS.map((t) => `        - ${t.actionKey}`).join('\n');

  return `# TraceFlow Forge app (TF-01, TF-04, TF-06). UNVERIFIED: not deployed yet.
#
# GENERATED by scripts/forge-manifest.mjs from the shared tool catalog
# (packages/core/src/tools.ts). Edit the script or the catalog, then run
# \`npm run forge:manifest\`; \`npm run forge:check\` (in verify and CI) validates
# this file with Atlassian's own manifest validator and fails when it is stale.
#
# One-time setup (see app/README.md):
#   1. forge login
#   2. forge register  -> writes the real app id into app.id below (kept by the script)
#   3. npm run forge:build && cd app && forge deploy --non-interactive -e development
app:
  id: ${appId}
  runtime:
    name: nodejs24.x
modules:
  jira:globalPage:
    - key: traceflow-workbench
      resource: workbench-ui
      resolver:
        function: tf-resolver
      title: TraceFlow
  function:
${functions}
  # Every TraceFlow tool is a read-only Rovo action (actionVerb GET) backed by
  # the shared catalog; the handlers live in app/src/backend/tools.ts.
  action:
${actions}
  # TF-06 inside Forge: the same actions as tools on Atlassian's MCP
  # infrastructure, for Rovo Studio agents and (once a site admin enables it)
  # external MCP clients at https://mcp.atlassian.com/forge/<app uuid>.
  rovo:mcp:
    - key: traceflow-mcp
      name: TraceFlow
      tools:
${toolKeys}
  rovo:agent:
    - key: traceflow-analyst
      name: TraceFlow Risk Analyst
      description: Reveals knowledge-continuity risks and decision lineage in this workspace, with the evidence records behind every answer.
      prompt: |
${indent(AGENT_PROMPT, 8)}
      conversationStarters:
        - What are the biggest knowledge risks right now?
        - What breaks if Alex leaves?
        - What are the top knowledge-continuity risks in the Payments reliability epic?
        - What happens if the idempotency key scope decision changes?
      actions:
${toolKeys}
resources:
  # A Custom UI resource is a DIRECTORY holding a prebuilt index.html. Forge does
  # not build it: \`npm run forge:build\` (vite) writes src/frontend/build first.
  - key: workbench-ui
    path: src/frontend/build
permissions:
  # Reads run as the viewing user (asUser), so Jira and Confluence permissions apply.
  scopes:
    - read:jira-work
    - read:jira-user
    - read:page:confluence
    - storage:app
  # No external permissions: fonts are bundled (Geist Mono) or system (General
  # Sans falls back by design, DESIGN.md rule 10), and nothing leaves Atlassian,
  # which keeps the app eligible for Runs on Atlassian.
`;
}

const mode = process.argv[2];
const rendered = renderManifest();
if (mode === '--write') {
  writeFileSync(manifestPath, rendered);
  console.log('forge-manifest: wrote app/manifest.yml');
} else if (mode === '--check') {
  const current = readFileSync(manifestPath, 'utf8');
  if (current !== rendered) {
    console.error('forge-manifest: app/manifest.yml is stale; run `npm run forge:manifest`');
    process.exit(1);
  }
  console.log('forge-manifest: app/manifest.yml matches the tool catalog');
} else if (mode === undefined) {
  process.stdout.write(rendered);
}
